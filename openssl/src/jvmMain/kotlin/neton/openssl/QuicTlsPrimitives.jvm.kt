package neton.openssl

internal actual object QuicTlsPrimitives {
    actual fun contextNew(server: Boolean, suites: String, groups: String?): Long = Jni.qtlsContextNew(server, suites, groups)
    actual fun contextFree(context: Long) = Jni.qtlsContextFree(context)
    actual fun contextVerify(context: Long, mode: Int) = Jni.qtlsContextVerify(context, mode)
    actual fun contextAnchor(context: Long, der: ByteArray): Int = Jni.qtlsContextAnchor(context, der)
    actual fun contextIdentity(context: Long, certs: ByteArray, sizes: IntArray, key: ByteArray, keyIsPem: Boolean): Int = Jni.qtlsContextIdentity(context, certs, sizes, key, keyIsPem)
    actual fun contextKeyLog(context: Long) = Jni.qtlsContextKeyLog(context)
    actual fun connectionNew(context: Long, server: Boolean, params: ByteArray, serverAlpn: ByteArray, keyLog: Boolean): Long = Jni.qtlsNew(context, server, params, serverAlpn, keyLog)
    actual fun connectionFree(connection: Long) = Jni.qtlsFree(connection)
    actual fun serverName(connection: Long, name: String, ip: Boolean): Boolean = Jni.qtlsServerName(connection, name, ip)
    actual fun offerAlpn(connection: Long, wire: ByteArray): Boolean = Jni.qtlsOfferAlpn(connection, wire)
    actual fun resume(connection: Long, der: ByteArray, early: Boolean, offered: ByteArray): Boolean = Jni.qtlsResume(connection, der, early, offered)
    actual fun enableEarlyData(connection: Long): Boolean = Jni.qtlsEnableEarlyData(connection)
    actual fun inject(connection: Long, callback: Int) = Jni.qtlsInject(connection, callback)
    actual fun provide(connection: Long, bytes: ByteArray): Boolean = Jni.qtlsProvide(connection, bytes)
    actual fun incoming(connection: Long): Int = Jni.qtlsIncoming(connection)
    actual fun drive(connection: Long, complete: Boolean): Int = Jni.qtlsDrive(connection, complete)
    actual fun initFinished(connection: Long): Boolean = Jni.qtlsInitFinished(connection)
    actual fun takeOutgoing(connection: Long, level: Int): ByteArray = Jni.qtlsTakeOutgoing(connection, level)
    actual fun takeSecret(connection: Long, level: Int, direction: Int): ByteArray? = Jni.qtlsTakeSecret(connection, level, direction)
    actual fun suite(connection: Long, level: Int): Int = Jni.qtlsSuite(connection, level)
    actual fun takeEarlySecret(connection: Long): ByteArray? = Jni.qtlsTakeEarlySecret(connection)
    actual fun peerParams(connection: Long): ByteArray? = Jni.qtlsPeerParams(connection)
    actual fun alert(connection: Long): Int = Jni.qtlsAlert(connection)
    actual fun failure(connection: Long): Int = Jni.qtlsFailure(connection)
    actual fun failureMessage(connection: Long): String = Jni.qtlsFailureMessage(connection)
    actual fun alpn(connection: Long): ByteArray? = Jni.qtlsAlpn(connection)
    actual fun sni(connection: Long): String? = Jni.qtlsSni(connection)
    actual fun earlyAccepted(connection: Long): Boolean = Jni.qtlsEarlyAccepted(connection)
    actual fun peerDer(connection: Long, index: Int): ByteArray? = Jni.qtlsPeerDer(connection, index)
    actual fun takeTickets(connection: Long): ByteArray = Jni.qtlsTakeTickets(connection)
    actual fun droppedTickets(connection: Long): Int = Jni.qtlsDroppedTickets(connection)
    actual fun takeKeyLog(connection: Long): ByteArray = Jni.qtlsTakeKeyLog(connection)
    actual fun export(connection: Long, output: ByteArray, label: String, context: ByteArray): Int = Jni.qtlsExport(connection, output, label, context)
    actual fun cleanShutdown(connection: Long) = Jni.qtlsCleanShutdown(connection)
}
